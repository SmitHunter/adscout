import { fireEvent, screen, waitFor, within } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import type { Report } from "@/api/client";
import { renderRoutes } from "@/features/watch/testing";

import { makeAd, makeAdvertiser, makeAnalysis, makeReport } from "./fixtures";
import { PrintReport } from "./PrintReport";

function printable(overrides: Partial<Report> = {}): Report {
  const ads = Array.from({ length: 8 }, (_, i) =>
    makeAd({ ad_archive_id: String(2000 + i), days_running: 300 - i * 10 }),
  );
  ads.push(makeAd({ ad_archive_id: "9999", relevant: false, reason: "no_keyword" }));
  const advertisers = Array.from({ length: 7 }, (_, i) =>
    makeAdvertiser({ key: `p${i}`, name: `Store ${i + 1}`, is_leader: i === 0 }),
  );
  return makeReport({ ads, advertisers, ...overrides });
}

function serve(report: Report | { status: number; detail: string }) {
  vi.stubGlobal(
    "fetch",
    vi.fn((input: RequestInfo | URL) => {
      const url = String(input);
      if (url.endsWith("/report") && "status" in report) {
        return Promise.resolve(
          new Response(JSON.stringify({ detail: report.detail }), { status: report.status }),
        );
      }
      const body = url.endsWith("/report") ? report : null;
      return Promise.resolve(new Response(JSON.stringify(body)));
    }),
  );
}

function renderPrint() {
  return renderRoutes([{ path: "/report/:id/print", element: <PrintReport /> }], "/report/1/print");
}

beforeEach(() => {
  document.documentElement.setAttribute("data-theme", "dark");
  window.localStorage.setItem("adscout-theme", "dark");
});

afterEach(() => {
  vi.unstubAllGlobals();
  window.localStorage.clear();
  document.body.removeAttribute("data-print-ready");
  document.body.removeAttribute("data-print-failed");
});

describe("PrintReport", () => {
  it("print route sets ready after images", async () => {
    serve(printable({ analysis: makeAnalysis() }));
    const view = renderPrint();

    expect(await screen.findByRole("heading", { name: "posture corrector" })).toBeInTheDocument();
    // Light, whatever the user picked, and their choice is left alone.
    expect(document.documentElement.getAttribute("data-theme")).toBe("light");
    expect(window.localStorage.getItem("adscout-theme")).toBe("dark");

    const tiles = screen.getAllByTestId("print-creative");
    expect(tiles).toHaveLength(6);
    const rows = within(screen.getByRole("table", { name: "Top advertisers" })).getAllByRole("row");
    expect(rows).toHaveLength(6); // header + 5
    expect(screen.getByTestId("analysis-verdict")).toBeInTheDocument();
    expect(screen.getByText("Generated by AdScout")).toBeInTheDocument();
    expect(screen.getAllByTestId("ruler-track").length).toBeGreaterThan(0);

    // Not ready while images are still loading.
    expect(document.body).not.toHaveAttribute("data-print-ready");
    const images = tiles.map((tile) => within(tile).getByRole("img"));
    images.slice(0, 5).forEach((img) => fireEvent.load(img));
    expect(document.body).not.toHaveAttribute("data-print-ready");

    // The last falls back from the saved file to the CDN, which fails too.
    const last = images[5] as HTMLImageElement;
    expect(last.getAttribute("src")).toBe("/media/1/2005_0.jpg");
    fireEvent.error(last);
    const retry = within(tiles[5] as HTMLElement).getByRole("img");
    expect(retry.getAttribute("src")).toBe("https://cdn.test/2005.jpg");
    fireEvent.error(retry);

    await waitFor(() => expect(document.body).toHaveAttribute("data-print-ready"));
    expect(within(tiles[5] as HTMLElement).getByText("Media unavailable")).toBeInTheDocument();

    view.unmount();
    expect(document.body).not.toHaveAttribute("data-print-ready");
    expect(document.documentElement.getAttribute("data-theme")).toBe("dark");
  });

  it("print omits verdict without analysis", async () => {
    serve(printable({ ads: [] }));
    renderPrint();

    expect(await screen.findByRole("heading", { name: "posture corrector" })).toBeInTheDocument();
    expect(screen.queryByTestId("analysis-verdict")).toBeNull();
    // Nothing to load: ready straight away.
    await waitFor(() => expect(document.body).toHaveAttribute("data-print-ready"));
  });

  it.each([
    [404, "not-found", "This report doesn't exist."],
    [500, "load", "Can't load this report."],
  ])("print signals failure on a %i", async (status, reason, text) => {
    serve({ status, detail: "Nope." });
    const view = renderPrint();

    expect(await screen.findByText(text)).toBeInTheDocument();
    await waitFor(() => expect(document.body).toHaveAttribute("data-print-failed", reason));
    // The exporter must never print the error page.
    expect(document.body).not.toHaveAttribute("data-print-ready");

    view.unmount();
    expect(document.body).not.toHaveAttribute("data-print-failed");
  });
});
